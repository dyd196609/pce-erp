export const BUSINESS_PRINT_VIEW_MODEL_VERSION_V11428427243 = 'V1.14.2.8.4.27.2.4.3'
export const PRINT_FORM_RULE_V11428427243 = 'PRINT-FORM-001'

const freeze = value => Object.freeze(value)
const text = value => String(value ?? '').trim()

function freezeRows(rows = []) {
  return freeze(rows.map(row => freeze({ ...row })))
}

/**
 * ERP打印单据的唯一展示契约。它是服务端/Provider事实的只读投影，
 * 不读取页面DOM，不持久化审批内容，也不推进任何业务状态。
 */
export function buildBusinessPrintViewModelV11428427243({
  companyInfo = {}, documentInfo = {}, basicInfo = {}, detailRows = [],
  approvalInfo = {}, printMeta = {},
} = {}) {
  const layout = basicInfo.layout === 'eight' ? 'eight' : 'six'
  const model = {
    version: BUSINESS_PRINT_VIEW_MODEL_VERSION_V11428427243,
    governanceRule: PRINT_FORM_RULE_V11428427243,
    companyInfo: freeze({ companyName: text(companyInfo.companyName) || '企业名称待配置' }),
    documentInfo: freeze({
      documentName: text(documentInfo.documentName),
      documentNo: text(documentInfo.documentNo),
      documentNoField: text(documentInfo.documentNoField),
    }),
    basicInfo: freeze({
      layout,
      columnCount: layout === 'eight' ? 8 : 6,
      fields: freezeRows(Array.isArray(basicInfo.fields) ? basicInfo.fields : []),
      longText: freezeRows(Array.isArray(basicInfo.longText) ? basicInfo.longText : []),
    }),
    detailRows: freezeRows(Array.isArray(detailRows) ? detailRows : []),
    approvalInfo: freeze({
      visible: approvalInfo.visible !== false,
      editable: approvalInfo.editable === true,
      slots: freezeRows(Array.isArray(approvalInfo.slots) ? approvalInfo.slots : []),
      autoGeneratedApprovalResult: false,
    }),
    printMeta: freeze({
      ...printMeta,
      generatedFromPageDom: false,
      businessWriteCount: 0,
    }),
  }
  return freeze(model)
}

