export const businessOperationPageConfigs = pages.map((page, index) => {
  const previousStepId = index > 0 ? pages[index - 1].pageStepId : 'incoming-inspection'
  const nextStepId = index < pages.length - 1 ? pages[index + 1].pageStepId : null
  const previousRoutePath = page.previousRoutePath || routeByStepId.get(previousStepId) || '/qms/incoming-inspections'
  const sourceRoutePath = page.sourceRoutePath || previousRoutePath
  const nextRoutePath = page.nextRoutePath ?? (nextStepId ? routeByStepId.get(nextStepId) : '')

  return {
    ...page,
    processName: '采购应付至正式付款凭证流程',
    browserTitle: page.pageTitle,
    previousStepId,
    previousRoutePath,
    sourceStepId: previousStepId,
    sourceStepName: page.previousStepName,
    sourceRoutePath,
    nextStepId,
    nextRoutePath,
    purposeText: `在“${page.pageTitle}”页面核对来源、状态、金额和业务条件，形成“${page.outputName}”，并为下一步“${page.nextStepName}”提供可追溯依据。`,
    prerequisiteItems: makePrerequisites(page.previousStepName, page.outputName),
    operationSequenceItems: makeSequenceItems(page.sourceButtonText, page.outputName, page.nextButtonText),
    emptyOutputText: `当前尚未形成${page.outputName}。`,
    outputFieldDefinitions: makeOutputFields(page.outputName),
    blockReasonDefinitions: [
      `当前${page.previousStepName}尚未完成，不能进入${page.pageTitle}。`,
      `当前${page.outputName}尚未形成，不能进入${page.nextStepName}。`,
      '当前来源单据无法识别。',
      '当前金额、供应商或业务状态待确认。',
    ],
    businessSectionIds: [`${page.pageStepId}-list`, `${page.pageStepId}-operation`],
    forbiddenMainSectionKeywords: [
      '核销',
      '总账写入',
      '过账',
      '银行流水生成',
      '真实付款执行',
      '模拟沙箱',
    ],
    technicalDiagnosticsEnabled: true,
    introducedInVersion: BUSINESS_OPERATION_PAGE_REGISTRY_VERSION,
  }
})

export function listBusinessOperationPageConfigs() {
  return businessOperationPageConfigs
}

export function findBusinessOperationPageConfig(pageStepIdOrRoutePath) {
  const value = String(pageStepIdOrRoutePath || '')
  return businessOperationPageConfigs.find((item) => item.pageStepId === value || item.routePath === value) || null
}
