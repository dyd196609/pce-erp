function resolveLabelObject(label, locale) {
  return label?.[locale] || label?.[defaultLocale] || label?.zh || label?.en || label?.key || ''
}

export function translate(key, locale = defaultLocale) {
  if (key == null) return ''

  if (typeof key === 'object') {
    return translate(resolveLabelObject(key, locale), locale)
  }

  const source = String(key)
  return dictionary[locale]?.[source] || dictionary[defaultLocale]?.[source] || source
}

export function translateSchemaLabel(schema = {}, locale = defaultLocale) {
  return translate(schema.labels || schema.label || schema.title || schema.meta?.title || schema.key || schema.name, locale)
}

export function applyI18n(schema = {}, locale = defaultLocale) {
  const title = translateSchemaLabel(schema, locale)
  const columns = (schema?.ui?.list?.columns || []).map((column) => ({
    ...column,
    label: translate(column.label || column.labels || column.key, locale),
  }))
  const actions = (schema?.ui?.list?.actions || []).map((action) => ({
    ...action,
    label: translate(action.label || action.labels || action.key || action.event, locale),
  }))

  return {
    ...schema,
    title,
    labels: {
      ...(schema.labels || {}),
      title,
      loading: translate('Loading', locale),
      noData: translate('No Data Available', locale),
      actionsColumn: translate('Actions', locale),
      blockedTitle: translate('Page Blocked by Review Control', locale),
      blockedMessage: translate('This page is restricted by review compliance control.', locale),
    },
    ui: {
      ...(schema.ui || {}),
      list: {
        ...(schema?.ui?.list || {}),
        columns,
        actions,
      },
    },
  }
}

export function getDictionary(locale = defaultLocale) {
  return dictionary[locale] || dictionary[defaultLocale]
}
