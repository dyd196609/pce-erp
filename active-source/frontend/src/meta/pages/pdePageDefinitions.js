export function resolvePdeNavigationTarget(label, fallbackPageCode = '') {
  if (PDE_NAVIGATION_BY_LABEL[label]) return PDE_NAVIGATION_BY_LABEL[label]
  const pageUrl = PDE_PAGE_URLS[fallbackPageCode] || ''
  return Object.freeze({ label, pageCode: fallbackPageCode, pageUrl })
}

export function resolvePdeFlowAdjacency(currentFlowStep, flowSteps = PDE_MAIN_FLOW) {
  const currentIndex = flowSteps.indexOf(currentFlowStep)
  if (currentIndex < 0) return null
  return Object.freeze({
    previous: flowSteps[currentIndex - 1] || '',
    current: currentFlowStep,
    next: flowSteps[currentIndex + 1] || '',
  })
}

const governance = ({
  pageCode,
  pageName,
  purpose,
  allowed,
  forbidden,
  currentFlowStep,
  previous,
  next,
  flowSteps = PDE_MAIN_FLOW,
}) => {
  const canonicalAdjacency = resolvePdeFlowAdjacency(currentFlowStep, flowSteps)
  const previousStep = previous ?? canonicalAdjacency?.previous ?? ''
  const nextStep = next ?? canonicalAdjacency?.next ?? ''
  return Object.freeze({
    version: PDE_PAGE_VERSION,
    frameworkVersion: 'PCE Enterprise Page V2',
    businessModule: 'PDE',
    pageName,
    pageCode,
    purpose,
    allowed: Object.freeze(allowed),
    forbidden: Object.freeze(forbidden),
    flowSteps,
    currentFlowStep,
    navigation: Object.freeze({
      previous: resolvePdeNavigationTarget(previousStep),
      current: resolvePdeNavigationTarget(pageName, pageCode),
      next: resolvePdeNavigationTarget(nextStep),
    }),
    returnModuleCode: 'PDE',
    positioning: '订单驱动的产品研发与工程资料管理中心',
  })
}

